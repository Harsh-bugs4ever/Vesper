def _load_ai_content(
    *,
    use_deepseek: bool,
    refresh_ai: bool,
) -> dict[str, Any]:

    if (
        AI_CACHE.exists()
        and not refresh_ai
    ):
        try:
            cached = json.loads(
                AI_CACHE.read_text(
                    encoding="utf-8"
                )
            )

            if cached.get("tasks") and (
                not use_deepseek or cached.get("model") == DEEPSEEK_MODEL
            ):
                return cached

        except (
            OSError,
            json.JSONDecodeError,
        ):
            pass

    if use_deepseek:
        generated = _generate_ai_content()
        if not generated.get("tasks"):
            raise RuntimeError("DeepSeek did not generate any valid tasks")
        AI_CACHE.parent.mkdir(parents=True, exist_ok=True)
        AI_CACHE.write_text(
            json.dumps(generated, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        return generated

    return _fallback_ai_content()


def _seed_ai_tasks(
    db,
    *,
    pid,
    departments,
    roles,
    users,
    rooms,
    ai_content,
    skip_existing: bool,
) -> int:

    import vesper_models.staff as staff

    existing_titles: set[str] = set()

    if skip_existing:
        existing_titles = {
            str(title)
            .strip()
            .lower()

            for title in db.scalars(
                select(
                    staff.Task.title
                ).where(
                    staff.Task.property_id
                    == pid
                )
            ).all()

            if title
        }

    members_by_department = {}

    for (
        key,
        department,
    ) in departments.items():

        members_by_department[
            key
        ] = [
            user
            for user in users

            if (
                user.role_id
                == roles["staff"].id

                and user.department_id
                == department.id
            )
        ]

    shuffled_rooms = list(
        rooms
    )

    random.shuffle(
        shuffled_rooms
    )

    room_cycle = itertools.cycle(
        shuffled_rooms
    )

    added = 0

    for item in ai_content.get(
        "tasks",
        [],
    ):

        department_key = str(
            item.get(
                "department",
                "",
            )
        ).strip()

        if (
            department_key
            not in departments
        ):
            continue

        members = (
            members_by_department
            .get(
                department_key,
                [],
            )
        )

        if not members:
            continue

        title = str(
            item.get(
                "title",
                "",
            )
        ).strip()

        description = str(
            item.get(
                "description",
                "",
            )
        ).strip()

        if (
            not title
            or not description
        ):
            continue

        if (
            title.lower()
            in existing_titles
        ):
            continue

        try:
            due_minutes = int(
                item.get(
                    "due_minutes",
                    90,
                )
            )
        except (
            TypeError,
            ValueError,
        ):
            due_minutes = 90

        room = None

        if bool(
            item.get(
                "room_related",
                False,
            )
        ):
            room = next(
                room_cycle
            )

        db.add(
            staff.Task(
                property_id=pid,

                department_id=(
                    departments[
                        department_key
                    ].id
                ),

                assignee_id=(
                    random.choice(
                        members
                    ).id
                ),

                room_id=(
                    room.id
                    if room
                    else None
                ),

                title=title[:180],

                description=(
                    description[:1200]
                ),

                status=(
                    staff
                    .TaskStatus
                    .ASSIGNED
                ),

                priority=(
                    staff
                    .TaskPriority
                    .NORMAL
                ),

                source=(
                    staff
                    .TaskSource
                    .MANUAL
                ),

                due_at=(
                    utcnow()
                    + timedelta(
                        minutes=due_minutes
                    )
                ),
            )
        )

        existing_titles.add(
            title.lower()
        )

        added += 1

    db.flush()

    return added


