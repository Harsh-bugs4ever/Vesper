def _demo_reference(index: int) -> str:
    digits = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"

    value = index
    out = ""

    while value:
        value, remainder = divmod(
            value,
            36,
        )

        out = (
            digits[remainder]
            + out
        )

    return (
        "VS"
        + (out or "0").rjust(
            6,
            "0",
        )
    )


def _demand_event_multiplier(
    day: date,
) -> float:
    multiplier = 1.0

    if day.month in {
        11,
        12,
        1,
        2,
    }:
        multiplier *= 1.06

    if (
        day.month == 12
        and day.day >= 20
    ):
        multiplier *= 1.18

    if (
        day.month == 1
        and day.day <= 5
    ):
        multiplier *= 1.12

    if (
        day.month == 2
        and 12 <= day.day <= 15
    ):
        multiplier *= 1.08

    if day.month in {
        6,
        7,
    }:
        multiplier *= 0.92

    return multiplier


def _deepseek_json(
    prompt: str,
) -> dict[str, Any]:

    api_key = os.getenv(
        "DEEPSEEK_API_KEY"
    )

    if not api_key:
        raise RuntimeError(
            "DEEPSEEK_API_KEY is not set; add it to .env or use --no-deepseek"
        )

    response = httpx.post(
        "https://api.deepseek.com/chat/completions",
        headers={"Authorization": f"Bearer {api_key}"},
        json={
            "model": DEEPSEEK_MODEL,
            "messages": [
                {
                    "role": "system",
                    "content": AI_SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],
            "temperature": 0.9,
            "thinking": {"type": "disabled"},
            "response_format": {"type": "json_object"},
            "max_tokens": 8192,
        },
        timeout=90.0,
    )
    response.raise_for_status()

    choices = response.json().get("choices") or []
    content = choices[0].get("message", {}).get("content") if choices else None
    if not isinstance(content, str) or not content.strip():
        raise RuntimeError("DeepSeek returned empty JSON content")

    payload = json.loads(content)
    if not isinstance(payload, dict):
        raise RuntimeError("DeepSeek returned a JSON value instead of an object")
    return payload


def _generate_ai_content() -> dict[str, Any]:
    all_tasks: list[
        dict[str, Any]
    ] = []

    for (
        department,
        department_name,
        _,
    ) in DEPARTMENTS:

        payload = _deepseek_json(
            f"""
Generate exactly {AI_TASKS_PER_DEPARTMENT}
meaningfully different operational tasks for the
{department_name} department.

Return exactly this JSON shape:

{{
  "tasks": [
    {{
      "department": "{department}",
      "title": "short title",
      "description": "specific operational description",
      "room_related": true,
      "due_minutes": 60
    }}
  ]
}}

Rules:
- department must always be "{department}".
- due_minutes must be one of:
  30, 45, 60, 90, 120, 180, 240.
- room_related is true only where assigning a guest
  room makes operational sense.
- Each task must represent a genuinely different situation.
- Do not reword the same issue.
- Mix routine work, exceptions, guest-impacting work,
  quality checks, handoffs, recovery tasks,
  preventive work and unusual-but-plausible situations.
"""
        )

        tasks = payload.get(
            "tasks",
            [],
        )

        if not isinstance(
            tasks,
            list,
        ):
            continue

        for item in tasks:
            if not isinstance(
                item,
                dict,
            ):
                continue

            title = str(
                item.get(
                    "title",
                    "",
                )
            ).strip()

            description = str(
                item.get(
                    "description",
                    "",
                )
            ).strip()

            if (
                not title
                or not description
            ):
                continue

            try:
                due = int(
                    item.get(
                        "due_minutes",
                        90,
                    )
                )
            except (
                TypeError,
                ValueError,
            ):
                due = 90

            if due not in {
                30,
                45,
                60,
                90,
                120,
                180,
                240,
            }:
                due = 90

            all_tasks.append(
                {
                    "department":
                        department,

                    "title":
                        title[:180],

                    "description":
                        description[:1200],

                    "room_related":
                        bool(
                            item.get(
                                "room_related",
                                False,
                            )
                        ),

                    "due_minutes":
                        due,
                }
            )

    seen: set[str] = set()

    unique: list[
        dict[str, Any]
    ] = []

    for item in all_tasks:
        key = " ".join(
            item["title"]
            .lower()
            .split()
        )

        if key in seen:
            continue

        seen.add(
            key
        )

        unique.append(
            item
        )

    return {
        "model":
            DEEPSEEK_MODEL,

        "generated_at":
            utcnow().isoformat(),

        "tasks":
            unique,
    }


